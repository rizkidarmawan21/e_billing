import { test, expect, login, submit, deleteRecord } from './helpers.js';

for (const role of ['admin', 'owner']) {
  test.describe(`${role} workflows`, () => {
    test.beforeEach(async ({ page }) => login(page, role));
    test('customer create, server validation, detail, edit, delete cancel/accept', async ({ page }) => {
      await page.goto('/customers/create');
      await page.locator('[name=kode_pelanggan]').fill('MOBILE-01-' + 'X'.repeat(70));
      await page.locator('[name=nama]').fill('Workflow Customer');
      await page.locator('[name=no_hp]').fill('081234567890');
      await page.locator('[name=alamat]').fill('Workflow address');
      await submit(page);
      await expect(page.locator('.alert-danger')).toBeVisible();
      await expect(page.locator('[name=nama]')).toHaveValue('Workflow Customer');
      await page.locator('[name=kode_pelanggan]').fill('WORKFLOW-CUSTOMER');
      await page.locator('[name=package_id]').selectOption('1');
      await submit(page);
      await expect(page).toHaveURL(/\/customers$/);
      await page.goto('/customers?search=Workflow');
      let row = page.locator('tbody tr').filter({ hasText: 'Workflow Customer' });
      const edit = await row.locator('a[href$="/edit"]').getAttribute('href');
      const detail = edit.replace(/\/edit$/, '');
      await page.goto(detail);
      await expect(page.locator('body')).toContainText('Workflow address');
      await page.goto(edit);
      await page.locator('[name=nama]').fill('Workflow Customer Updated');
      await submit(page);
      await page.goto('/customers?search=Workflow');
      row = page.locator('tbody tr').filter({ hasText: 'Workflow Customer Updated' });
      await deleteRecord(page, row);
      await expect(page.locator('tbody')).not.toContainText('Workflow Customer Updated');
    });
    test('package create, duplicate validation, detail, update and delete', async ({ page }) => {
      await page.goto('/packages/create');
      await page.locator('[name=nama_paket]').fill('Mobile Package 01 ' + 'FiberLong'.repeat(10));
      await page.locator('[name=kecepatan]').fill('200 Mbps');
      await page.locator('[name=harga]').fill('200000');
      await page.locator('[name=deskripsi]').fill('Workflow package description');
      await submit(page);
      await expect(page.locator('.alert-danger')).toBeVisible();
      await page.locator('[name=nama_paket]').fill('Workflow Package');
      await submit(page);
      await expect(page).toHaveURL(/\/packages$/);
      let row = page.locator('tbody tr').filter({ hasText: 'Workflow Package' });
      const edit = await row.locator('a[href$="/edit"]').getAttribute('href');
      await page.goto(edit.replace(/\/edit$/, ''));
      await expect(page.locator('body')).toContainText('Workflow package description');
      await page.goto(edit);
      await page.locator('[name=nama_paket]').fill('Workflow Package Updated');
      await submit(page);
      row = page.locator('tbody tr').filter({ hasText: 'Workflow Package Updated' });
      await deleteRecord(page, row);
    });
    test('payment create, duplicate validation, detail, update and delete', async ({ page }) => {
      await page.goto('/payments/create');
      await page.locator('#customer_search').fill('Mobile Customer 01');
      await page.locator('#customer_results button').first().click();
      await expect(page.locator('[name=customer_id]')).toHaveValue('1');
      await expect(page.locator('[name=package_id]')).toHaveValue('1');
      await page.locator('[name=periode]').selectOption('Januari');
      await submit(page);
      await expect(page.locator('.alert-danger')).toBeVisible();
      // Re-select after validation so this tests the supported UI, not hidden input mutation.
      await page.locator('#customer_search').fill('Mobile Customer 01');
      await page.locator('#customer_results button').first().click();
      await page.locator('[name=periode]').selectOption('Desember');
      await submit(page);
      await expect(page).toHaveURL(/\/payments$/);
      await page.goto('/payments/1');
      let row = page.locator('tbody tr').filter({ hasText: 'Desember' });
      const edit = await row.locator('a[href*="/edit"]').getAttribute('href');
      await page.goto(edit.replace(/\/edit.*$/, ''));
      await expect(page.locator('body')).toContainText('Mobile Customer 01');
      await page.goto(edit);
      await page.locator('[name=status]').selectOption('lunas');
      await expect(page.locator('[name=tanggal_bayar]')).toHaveAttribute('required', '');
      await page.locator('[name=tanggal_bayar]').fill('2026-01-15');
      await submit(page);
      await page.goto('/payments/1');
      row = page.locator('tbody tr').filter({ hasText: 'Desember' });
      await expect(row).toContainText('Lunas');
      await deleteRecord(page, row);
    });
    test('unpaid filter, pagination and edit preserve return filters', async ({ page }) => {
      await page.goto('/payments/unpaid');
      await page.locator('[name=search]').fill('Mobile Customer');
      const january = page.locator('[name="months[]"][value=Januari]');
      if (!await january.isVisible()) await page.getByRole('button', { name: 'Filter Bulan', exact: true }).click();
      await page.locator('[name=filter_active]').check();
      await january.check();
      await page.locator('.filter-menu').getByRole('button', { name: 'Terapkan', exact: true }).click();
      await expect(page).toHaveURL(/filter_active=1/);
      const next = page.locator('a[href*="page=2"]').first();
      await expect(next).toHaveAttribute('href', /search=Mobile/);
      await expect(next).toHaveAttribute('href', /Januari/);
      await next.click();
      const edit = page.locator('tbody a[href*="/edit"]').first();
      await edit.click();
      await expect(page).toHaveURL(/from_unpaid=1/);
      await page.locator('[name=jumlah_tagihan]').fill('160000');
      await submit(page);
      const url = new URL(page.url());
      expect(url.pathname).toBe('/payments/unpaid');
      expect(url.searchParams.get('search')).toBe('Mobile Customer');
      expect(url.searchParams.get('page')).toBe('2');
      expect([...url.searchParams.values()]).toContain('Januari');
    });
    test('customer search and pagination retain filter; empty results', async ({ page }) => {
      await page.goto('/customers');
      await page.locator('[name=search]').fill('Mobile Customer');
      await page.locator('[name=search]').press('Enter');
      await page.locator('a[href*="page=2"]').first().click();
      expect(new URL(page.url()).searchParams.get('search')).toBe('Mobile Customer');
      await expect(page.locator('tbody tr')).toHaveCount(2);
      await page.locator('[name=search]').fill('No such isolated customer');
      await page.locator('[name=search]').press('Enter');
      await expect(page.locator('tbody')).not.toContainText('Mobile Customer');
    });
    test('profile update, invalid current password and password update/login', async ({ page }) => {
      await page.goto('/profile');
      await page.locator('[name=name]').fill('Workflow Profile');
      await page.locator('form').filter({ has: page.locator('[name=email]') }).getByRole('button', { name: /Simpan/ }).click();
      await page.reload();
      await expect(page.locator('[name=name]')).toHaveValue('Workflow Profile');
      const form = page.locator('form').filter({ has: page.locator('[name=current_password]') });
      await form.locator('[name=current_password]').fill('wrong-password');
      await form.locator('[name=password]').fill('ChangedMobile!234');
      await form.locator('[name=password_confirmation]').fill('ChangedMobile!234');
      await form.getByRole('button', { name: /Simpan/ }).click();
      await expect(page.locator('body')).toContainText(/incorrect|salah|tidak sesuai/i);
      await form.locator('[name=current_password]').fill('MobileTest!234');
      await form.locator('[name=password]').fill('ChangedMobile!234');
      await form.locator('[name=password_confirmation]').fill('ChangedMobile!234');
      await form.getByRole('button', { name: /Simpan/ }).click();
      await expect(page.locator('body')).toContainText(/Password berhasil/i);
      await page.context().clearCookies();
      await login(page, role, 'ChangedMobile!234');
    });
  });
}

test('owner admin create, invalid confirmation, update and delete', async ({ page }) => {
  await login(page, 'owner');
  await page.goto('/owner/admin/create');
  await page.locator('[name=name]').fill('Workflow Admin');
  await page.locator('[name=email]').fill('workflow@mobile.test');
  await page.locator('[name=password]').fill('MobileTest!234');
  await page.locator('[name=password_confirmation]').fill('different-password');
  await submit(page);
  await expect(page.locator('[name=password]')).toHaveClass(/is-invalid/);
  await expect(page.locator('body')).toContainText(/confirmation|konfirmasi/i);
  await page.locator('[name=password]').fill('MobileTest!234');
  await page.locator('[name=password_confirmation]').fill('MobileTest!234');
  await submit(page);
  await expect(page).toHaveURL(/\/owner\/admin$/);
  let row = page.locator('tbody tr').filter({ hasText: 'workflow@mobile.test' });
  await row.locator('a[href$="/edit"]').click();
  await page.locator('[name=name]').fill('Workflow Admin Updated');
  await submit(page);
  row = page.locator('tbody tr').filter({ hasText: 'workflow@mobile.test' });
  await expect(row).toContainText('Workflow Admin Updated');
  await deleteRecord(page, row);
});
